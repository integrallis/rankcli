import { exec } from 'child_process';
import { promisify } from 'util';
import {
  runDirectAnalysis,
  generateFixes,
  applyFixes,
  detectFramework,
  type SEOAnalysisResult,
  type GeneratedFix,
  type FrameworkInfo,
} from '@rankcli/agent-runtime';
import ora from 'ora';
import chalk from 'chalk';
import { isLoggedIn, getUserInfo, WEB_APP_URL } from '../lib/config.js';
import { showUpsell, hasFeature, type TierId } from '../lib/upsell.js';

const execAsync = promisify(exec);

export interface FixOptions {
  url?: string;
  auto?: boolean;
  commit?: boolean;
  push?: boolean;
  dryRun?: boolean;
  only?: string[];
  output?: 'text' | 'json';
  cwd?: string;
}

export interface FixResult {
  success: boolean;
  error?: string;
  url?: string;
  dryRun?: boolean;
  fixes?: GeneratedFix[];
  appliedCount?: number;
  skippedCount?: number;
  durationMs?: number;
  commitMessage?: string;
  committed?: boolean;
  pushed?: boolean;
  commitError?: string;
  pushError?: string;
  json?: string;
}

const SEVERITY_ICON: Record<string, string> = {
  critical: '❌',
  error: '❌',
  warning: '⚠️',
  notice: 'ℹ️',
  info: 'ℹ️',
};

/**
 * Generate a conventional commit message for SEO fixes
 */
function generateCommitMessage(fixes: GeneratedFix[], url: string): string {
  const applied = fixes.filter(f => f.applied && !f.skipped);
  
  if (applied.length === 0) {
    return '';
  }

  // Determine commit type: feat for new elements, fix for corrections
  const isAddingNew = applied.some(f => 
    f.issue.code.includes('MISSING') || 
    f.issue.message.toLowerCase().includes('missing') ||
    f.issue.message.toLowerCase().includes('add')
  );
  
  const type = isAddingNew ? 'feat' : 'fix';

  // Fix.issue never carries a category (see agent-runtime's fixer.ts -
  // every generated fix's issue is a hardcoded { code, message, severity }
  // literal), so this has only ever produced 'seo'. Keep that behavior
  // explicit rather than a dead Set-based grouping over a field that
  // doesn't exist.
  const categoryStr = 'seo';

  // Build commit title
  const issueCount = applied.length;
  const title = `${type}(${categoryStr}): fix ${issueCount} SEO issue${issueCount > 1 ? 's' : ''}`;
  
  // Build commit body
  const fixList = applied
    .map(f => `- ${f.issue.code}: ${f.issue.message}`)
    .join('\n');
  
  const body = `Fixed:\n${fixList}\n\nURL: ${url}\nGenerated by: rankcli fix`;
  
  return `${title}\n\n${body}`;
}

/**
 * Execute git commands for committing and pushing
 */
async function executeGitCommit(
  cwd: string,
  commitMessage: string,
  push: boolean
): Promise<{ committed: boolean; pushed: boolean; error?: string }> {
  try {
    // Stage all changes
    await execAsync('git add -A', { cwd });
    
    // Commit with message
    const escapedMessage = commitMessage.replace(/"/g, '\\"');
    await execAsync(`git commit -m "${escapedMessage}"`, { cwd });
    
    let pushed = false;
    
    if (push) {
      try {
        await execAsync('git push', { cwd });
        pushed = true;
      } catch (pushErr) {
        return {
          committed: true,
          pushed: false,
          error: `Push failed: ${pushErr instanceof Error ? pushErr.message : 'Unknown error'}`,
        };
      }
    }
    
    return { committed: true, pushed };
  } catch (err) {
    return {
      committed: false,
      pushed: false,
      error: err instanceof Error ? err.message : 'Git operation failed',
    };
  }
}

function truncate(str: string, maxLen: number): string {
  const oneLine = str.replace(/\n/g, ' ').trim();
  if (oneLine.length <= maxLen) return oneLine;
  return oneLine.substring(0, maxLen - 3) + '...';
}

function printFix(fix: GeneratedFix, index: number): void {
  const icon = SEVERITY_ICON[fix.issue.severity] || '•';
  console.log(`\n${index + 1}. ${icon} ${fix.issue.message}`);
  console.log(`   Code: ${chalk.dim(fix.issue.code)}`);
  console.log(`   File: ${chalk.cyan(fix.file)}`);
  
  if (fix.skipped) {
    console.log(`   Status: ${chalk.yellow('SKIPPED')} - ${fix.skipReason}`);
  } else if (fix.applied) {
    console.log(`   Status: ${chalk.green('APPLIED')}`);
    console.log(`   ${chalk.dim('Explanation:')} ${fix.explanation}`);
  } else {
    console.log(`   ${chalk.dim('Explanation:')} ${fix.explanation}`);
    if (fix.before) {
      console.log(`   ${chalk.red('Before:')} ${truncate(fix.before, 60)}`);
    }
    console.log(`   ${chalk.green('After:')} ${truncate(fix.after, 100)}`);
  }
}

/**
 * Main fix command - detects issues, generates fixes, applies them, and optionally commits
 */
export async function fix(options: FixOptions): Promise<FixResult> {
  const startTime = Date.now();
  const cwd = options.cwd || process.cwd();
  const url = options.url;

  // Validate URL
  if (!url) {
    const error = 'Please provide a URL to fix:\n   rankcli fix --url https://your-site.com';
    if (options.output !== 'json') {
      console.log(`\n⚠️  ${error}\n`);
    }
    return { success: false, error };
  }

  try {
    new URL(url);
  } catch {
    const error = 'Invalid URL format. Please provide a valid URL.';
    if (options.output !== 'json') {
      console.log(`\n❌ ${error}\n`);
    }
    return { success: false, error };
  }

  // Check authentication and tier
  const loggedIn = isLoggedIn();
  const userInfo = getUserInfo();
  const tier = (userInfo.planName?.toLowerCase() || 'free') as TierId;
  
  // Auto-fix requires Solo tier or higher (unless dry-run)
  const hasAutoFix = loggedIn && hasFeature(tier, 'auto_fix');
  
  if (!options.dryRun && !hasAutoFix) {
    if (options.output !== 'json') {
      showUpsell('auto_fix_blocked');
    }
    return { 
      success: false, 
      error: 'Auto-fix requires Solo tier or higher. Please upgrade at ' + WEB_APP_URL + '/account',
    };
  }

  if (options.output !== 'json') {
    console.log('\n🔧 RankCLI Fix - Agentic SEO Fixer');
    console.log('═'.repeat(50));
  }

  // Detect framework
  const frameworkSpinner = options.output !== 'json' ? ora('Detecting framework...').start() : null;
  
  const frameworkResult = await detectFramework({ cwd });
  const framework = frameworkResult.success
    ? (frameworkResult.data as FrameworkInfo)
    : { name: 'Unknown', metaPattern: 'html-head' as const };
  
  frameworkSpinner?.succeed(`Framework: ${framework.name}`);

  // Analyze URL
  const analyzeSpinner = options.output !== 'json' ? ora(`Analyzing ${url}...`).start() : null;

  let issues: SEOAnalysisResult['issues'];
  let score: number;

  try {
    const analysis = await runDirectAnalysis(url);
    issues = analysis.issues;
    score = analysis.score;
  } catch (error) {
    const errorMsg = error instanceof Error ? error.message : 'Unknown error';
    analyzeSpinner?.fail(`Analysis failed: ${errorMsg}`);
    return { success: false, error: `Analysis failed: ${errorMsg}` };
  }

  analyzeSpinner?.succeed(`Score: ${score}/100, Issues: ${issues.length}`);

  // Filter issues if --only flag is used
  if (options.only && options.only.length > 0) {
    const onlyCodes = new Set(options.only.map(c => c.toUpperCase()));
    issues = issues.filter(i => onlyCodes.has(i.code.toUpperCase()));
    
    if (options.output !== 'json') {
      console.log(chalk.dim(`   Filtered to ${issues.length} issue(s) matching: ${options.only.join(', ')}`));
    }
  }

  if (issues.length === 0) {
    if (options.output !== 'json') {
      console.log('\n✅ No issues found! Your site looks great.\n');
    }
    return {
      success: true,
      url,
      dryRun: options.dryRun,
      fixes: [],
      appliedCount: 0,
      skippedCount: 0,
      durationMs: Date.now() - startTime,
    };
  }

  // Generate fixes
  const fixSpinner = options.output !== 'json' ? ora('Generating fixes...').start() : null;

  const fixes = await generateFixes(issues, {
    cwd,
    url,
    framework,
  });

  const actionableFixes = fixes.filter(f => !f.skipped);
  const skippedFixes = fixes.filter(f => f.skipped);

  fixSpinner?.succeed(`Generated ${actionableFixes.length} fix(es), ${skippedFixes.length} skipped`);

  // Dry run mode - don't apply changes
  if (options.dryRun) {
    if (options.output !== 'json') {
      console.log('\n' + '─'.repeat(50));
      console.log(chalk.yellow('DRY RUN - No changes will be made'));
      console.log('─'.repeat(50));
      
      for (let i = 0; i < fixes.length; i++) {
        printFix(fixes[i], i);
      }
      
      console.log('\n' + '─'.repeat(50));
      console.log(`📋 ${chalk.bold('Summary:')} ${actionableFixes.length} fix(es) would be applied`);
      console.log(`   Remove --dry-run to apply these fixes.\n`);
    }

    const result: FixResult = {
      success: true,
      url,
      dryRun: true,
      fixes,
      appliedCount: 0,
      skippedCount: skippedFixes.length,
      durationMs: Date.now() - startTime,
    };

    if (options.output === 'json') {
      result.json = JSON.stringify({
        url,
        dryRun: true,
        fixes: fixes.map(f => ({
          code: f.issue.code,
          message: f.issue.message,
          file: f.file,
          skipped: f.skipped,
          skipReason: f.skipReason,
        })),
        appliedCount: 0,
        skippedCount: skippedFixes.length,
        durationMs: result.durationMs,
      }, null, 2);
    }

    return result;
  }

  // Apply fixes
  if (actionableFixes.length === 0) {
    if (options.output !== 'json') {
      console.log('\n⚠️  No automatic fixes available. Please address issues manually.\n');
    }
    return {
      success: true,
      url,
      fixes,
      appliedCount: 0,
      skippedCount: skippedFixes.length,
      durationMs: Date.now() - startTime,
    };
  }

  // Check for auto mode
  if (!options.auto) {
    if (options.output !== 'json') {
      console.log('\n' + '─'.repeat(50));
      console.log('PROPOSED FIXES:');
      console.log('─'.repeat(50));
      
      for (let i = 0; i < fixes.length; i++) {
        printFix(fixes[i], i);
      }
      
      console.log('\n' + '─'.repeat(50));
      console.log(`Ready to apply ${actionableFixes.length} fix(es).`);
      console.log('Run with --auto to apply without confirmation.');
      console.log('Run with --dry-run to preview changes.\n');
    }
    
    return {
      success: true,
      url,
      fixes,
      appliedCount: 0,
      skippedCount: skippedFixes.length,
      durationMs: Date.now() - startTime,
    };
  }

  // Apply fixes
  const applySpinner = options.output !== 'json' ? ora('Applying fixes...').start() : null;

  const { applied, skipped } = await applyFixes(fixes, { cwd, dryRun: false });
  
  // Mark fixes as applied
  for (const fix of applied) {
    fix.applied = true;
  }

  applySpinner?.succeed(`Applied ${applied.length} fix(es)`);

  // Generate commit message
  const commitMessage = options.commit ? generateCommitMessage(fixes, url) : undefined;

  let committed = false;
  let pushed = false;
  let commitError: string | undefined;
  let pushError: string | undefined;

  // Execute git operations if requested
  if (options.commit && applied.length > 0 && commitMessage) {
    const gitSpinner = options.output !== 'json' ? ora('Committing changes...').start() : null;
    
    const gitResult = await executeGitCommit(cwd, commitMessage, options.push || false);
    committed = gitResult.committed;
    pushed = gitResult.pushed;
    
    if (gitResult.error) {
      if (gitResult.error.includes('Push')) {
        pushError = gitResult.error;
        gitSpinner?.warn('Committed but push failed');
      } else {
        commitError = gitResult.error;
        gitSpinner?.warn(`Commit failed: ${gitResult.error}`);
      }
    } else {
      if (pushed) {
        gitSpinner?.succeed('Committed and pushed');
      } else {
        gitSpinner?.succeed('Committed');
      }
    }
  }

  // Print results
  if (options.output !== 'json') {
    console.log('\n' + '═'.repeat(50));
    console.log('RESULTS');
    console.log('═'.repeat(50));

    if (applied.length > 0) {
      console.log(`\n${chalk.green('✅')} Applied ${applied.length} fix(es):`);
      for (const fix of applied) {
        console.log(`   - ${fix.file}: ${fix.issue.message}`);
      }
    }

    if (skipped.length > 0) {
      console.log(`\n${chalk.yellow('⚠️')} Skipped ${skipped.length} fix(es):`);
      for (const fix of skipped) {
        console.log(`   - ${fix.file}: ${fix.skipReason || 'Manual fix required'}`);
      }
    }

    if (committed) {
      console.log(`\n${chalk.green('✅')} Changes committed`);
      if (pushed) {
        console.log(`${chalk.green('✅')} Changes pushed`);
      }
    }

    // Next steps
    if (!committed && applied.length > 0) {
      console.log('\n' + '─'.repeat(50));
      console.log('NEXT STEPS:');
      console.log('─'.repeat(50));
      console.log('1. Review the changes:');
      console.log('   git diff');
      console.log('\n2. Commit the SEO improvements:');
      console.log(`   git add -A && git commit -m "feat(seo): fix ${applied.length} SEO issues"`);
      console.log('\n3. Re-run the audit to verify:');
      console.log(`   rankcli audit --url ${url}`);
    }
    
    console.log('');
  }

  const result: FixResult = {
    success: true,
    url,
    dryRun: false,
    fixes,
    appliedCount: applied.length,
    skippedCount: skipped.length,
    durationMs: Date.now() - startTime,
    commitMessage,
    committed,
    pushed,
    commitError,
    pushError,
  };

  if (options.output === 'json') {
    result.json = JSON.stringify({
      url,
      fixes: fixes.map(f => ({
        code: f.issue.code,
        message: f.issue.message,
        file: f.file,
        applied: f.applied,
        skipped: f.skipped,
        skipReason: f.skipReason,
      })),
      appliedCount: applied.length,
      skippedCount: skipped.length,
      durationMs: result.durationMs,
      committed,
      pushed,
      commitMessage,
    }, null, 2);
  }

  return result;
}
