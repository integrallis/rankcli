// GitHub Action Workflow Generator
// Creates a scheduled RankCLI SEO audit + auto-fix-PR workflow, built only
// from commands that actually exist in @rankcli/cli today (`audit`, `fix`) -
// earlier versions of this generator referenced a package that was never
// published (@seo-autopilot/cli) and CLI subcommands that don't exist
// (`seo report --combine`, `seo sync`), so every workflow it ever wrote was
// broken from the first run. See CLI's src/index.ts for the real command
// surface if this ever needs extending.

export interface WorkflowConfig {
  schedule: 'daily' | 'weekly' | 'monthly' | 'manual';
  siteUrl: string;
  features: {
    audit: boolean;
    autoFix: boolean;
    createIssues: boolean;
    createPRs: boolean;
  };
  // If set, the workflow adds RANKCLI_API_KEY as a required secret and
  // audits sync to the RankCLI dashboard automatically - `rankcli audit`
  // already does this itself when logged in, no separate sync step needed.
  syncToDashboard?: boolean;
}

/**
 * Generate GitHub Action workflow YAML
 */
export function generateWorkflow(config: WorkflowConfig): string {
  const cronSchedule = getCronSchedule(config.schedule);

  return `# RankCLI - Automated SEO Monitoring
# https://rankcli.dev - generated by \`rankcli setup --github-action\`

name: RankCLI SEO Check

on:
  schedule:
    - cron: '${cronSchedule}'

  workflow_dispatch:

env:
  SITE_URL: '${config.siteUrl}'

jobs:
  seo-check:
    runs-on: ubuntu-latest
    permissions:
      contents: write
      issues: write
      pull-requests: write

    steps:
      - name: Checkout repository
        uses: actions/checkout@v4

      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '20'

      - name: Install RankCLI
        run: npm install -g @rankcli/cli
${config.syncToDashboard ? `
      - name: Log in to RankCLI
        env:
          RANKCLI_API_KEY: \${{ secrets.RANKCLI_API_KEY }}
        run: rankcli login --token "$RANKCLI_API_KEY"
` : ''}
      - name: Run SEO audit
        run: |
          rankcli audit --url "$SITE_URL" --output json > audit-report.json
${config.features.createIssues ? `
      - name: Create/update SEO report issue
        uses: actions/github-script@v7
        with:
          script: |
            const fs = require('fs');
            const report = JSON.parse(fs.readFileSync('audit-report.json', 'utf8'));
            const errors = report.issues.filter(i => i.severity === 'error');
            const warnings = report.issues.filter(i => i.severity === 'warning');
            const notices = report.issues.filter(i => i.severity === 'notice');

            const lines = [
              \`## RankCLI SEO Report\`,
              '',
              \`**Score:** \${report.score}/100 · **Errors:** \${errors.length} · **Warnings:** \${warnings.length} · **Notices:** \${notices.length}\`,
              '',
            ];
            if (errors.length > 0) {
              lines.push('### Errors', ...errors.slice(0, 15).map(i => \`- \${i.title}\`), '');
            }
            if (warnings.length > 0) {
              lines.push('### Warnings', ...warnings.slice(0, 15).map(i => \`- \${i.title}\`), '');
            }
            if (report.dashboardUrl) {
              lines.push(\`[View full report on the RankCLI dashboard](\${report.dashboardUrl})\`);
            }
            const body = lines.join('\\n');
            const title = 'SEO Report - ' + new Date().toISOString().split('T')[0];

            const issues = await github.rest.issues.listForRepo({
              owner: context.repo.owner,
              repo: context.repo.repo,
              labels: 'seo-report',
              state: 'open',
            });

            if (issues.data.length > 0) {
              await github.rest.issues.update({
                owner: context.repo.owner,
                repo: context.repo.repo,
                issue_number: issues.data[0].number,
                body,
              });
            } else {
              await github.rest.issues.create({
                owner: context.repo.owner,
                repo: context.repo.repo,
                title,
                body,
                labels: ['seo-report', 'automated'],
              });
            }
` : ''}${config.features.autoFix && config.features.createPRs ? `
      - name: Auto-fix issues
        run: rankcli fix --url "$SITE_URL" --auto --output json > fixes.json

      - name: Check if any fixes were applied
        id: fixes
        run: |
          APPLIED=$(node -p "JSON.parse(require('fs').readFileSync('fixes.json','utf8')).appliedCount || 0")
          echo "applied=$APPLIED" >> $GITHUB_OUTPUT

      - name: Create PR with fixes
        if: steps.fixes.outputs.applied != '0'
        uses: peter-evans/create-pull-request@v6
        with:
          token: \${{ secrets.GITHUB_TOKEN }}
          commit-message: 'fix(seo): automated SEO improvements'
          title: '🔧 SEO Auto-Fix: Automated Improvements'
          body: |
            ## Automated SEO Fixes

            This PR was automatically generated by [RankCLI](https://rankcli.dev).

            ### Review Checklist
            - [ ] Changes look correct
            - [ ] No unintended modifications
            - [ ] Tests pass
          branch: rankcli-autofix-\${{ github.run_number }}
          labels: seo, automated
` : ''}
      - name: Save report artifact
        uses: actions/upload-artifact@v4
        with:
          name: rankcli-report-\${{ github.run_number }}
          path: |
            audit-report.json
            ${config.features.autoFix ? 'fixes.json' : ''}
          retention-days: 90
`;
}

function getCronSchedule(schedule: WorkflowConfig['schedule']): string {
  switch (schedule) {
    case 'daily':
      return '0 9 * * *'; // 9 AM UTC daily
    case 'weekly':
      return '0 9 * * 1'; // 9 AM UTC every Monday
    case 'monthly':
      return '0 9 1 * *'; // 9 AM UTC first of month
    case 'manual':
      return '0 0 31 2 *'; // Never (Feb 31 doesn't exist)
    default:
      return '0 9 * * 1';
  }
}

/**
 * Generate the secrets documentation
 */
export function generateSecretsDoc(config: WorkflowConfig): string {
  let secrets = `# Required GitHub Secrets

Go to your repository Settings > Secrets and variables > Actions

`;

  if (config.syncToDashboard) {
    secrets += `
## RankCLI (required - sends audits to your dashboard)

1. \`RANKCLI_API_KEY\`
   - Get a free API key at https://rankcli.dev/account?tab=api-keys
   - Without this secret, remove the "Log in to RankCLI" step from
     .github/workflows/seo.yml - the audit still runs, it just won't
     appear on your dashboard.

`;
  } else {
    secrets += `
No secrets are required for this workflow as configured - it runs a local
audit and, if enabled, opens auto-fix PRs using the repository's built-in
GITHUB_TOKEN. To also sync results to your RankCLI dashboard, re-run
\`rankcli setup --github-action\` and opt in when asked, or add a
\`RANKCLI_API_KEY\` secret and a \`rankcli login --token\` step yourself.

`;
  }

  return secrets;
}

/**
 * Generate complete setup package
 */
export function generateGitHubActionSetup(config: WorkflowConfig): {
  workflowYaml: string;
  secretsDoc: string;
  readmeBadge: string;
} {
  return {
    workflowYaml: generateWorkflow(config),
    secretsDoc: generateSecretsDoc(config),
    readmeBadge: `[![SEO Status](https://github.com/YOUR_ORG/YOUR_REPO/actions/workflows/seo.yml/badge.svg)](https://github.com/YOUR_ORG/YOUR_REPO/actions/workflows/seo.yml)`,
  };
}

/**
 * Write GitHub Action files to project
 */
export function writeGitHubActionFiles(
  projectPath: string,
  config: WorkflowConfig
): { files: string[]; instructions: string } {
  const fs = require('fs');
  const path = require('path');

  const files: string[] = [];

  // Create .github/workflows directory
  const workflowDir = path.join(projectPath, '.github', 'workflows');
  if (!fs.existsSync(workflowDir)) {
    fs.mkdirSync(workflowDir, { recursive: true });
  }

  // Write workflow file
  const workflowPath = path.join(workflowDir, 'seo.yml');
  fs.writeFileSync(workflowPath, generateWorkflow(config));
  files.push(workflowPath);

  // Write secrets documentation
  const docsDir = path.join(projectPath, '.github');
  const secretsDocPath = path.join(docsDir, 'SEO_SETUP.md');
  fs.writeFileSync(secretsDocPath, generateSecretsDoc(config));
  files.push(secretsDocPath);

  const instructions = config.syncToDashboard
    ? `
GitHub Action created! Next steps:

1. Add the RANKCLI_API_KEY secret to your repository:
   Settings > Secrets and variables > Actions
   Get a key at https://rankcli.dev/account?tab=api-keys
   See .github/SEO_SETUP.md for details

2. The workflow will run ${config.schedule}
   Or trigger manually: Actions > RankCLI SEO Check > Run workflow
`
    : `
GitHub Action created! No secrets required to run as-is.

1. Commit and push .github/workflows/seo.yml
2. The workflow will run ${config.schedule}
   Or trigger manually: Actions > RankCLI SEO Check > Run workflow
3. Want audits on your RankCLI dashboard too? Re-run
   \`rankcli setup --github-action\` and opt in - see .github/SEO_SETUP.md
`;

  return { files, instructions };
}
