// SEO fixes that need no model.
//
// Most of what a neglected site is missing is not a judgement call: robots.txt, a sitemap,
// llms.txt and a WebSite/Organization JSON-LD block are all derivable from two facts we
// already hold - the site's URL and its name. Generating them here means an account with no
// AI key still gets a useful pull request, with three properties an LLM can't offer:
// identical output every time, nothing invented, and the customer's source never leaves.
//
// Everything here is additive. Files are only created when absent, and the one existing file
// it touches - index.html - is edited by inserting a block before </head>, never by handing
// a model the whole file and committing whatever comes back.

import { generateAIFriendlyRobotsTxt } from '../analyzers/geo-analyzer.js';
import { generateOrganizationSchema, generateWebSiteSchema } from './schemas.js';

export interface DeterministicFixInput {
  siteUrl: string;
  siteName: string;
  /** Monorepo app root, '' at the repository root. Every emitted path starts with it. */
  appRoot: string;
  /**
   * Where files served at the site root live, relative to appRoot. 'public/' for Vite, CRA
   * and most bundlers; '' for a static site that serves its directory as-is (GitHub Pages
   * from docs/), where a public/ subdirectory would simply never be served. Defaults to
   * 'public/' because that is the common case, but getting it wrong means committing a
   * robots.txt nobody can fetch.
   */
  publicDir?: string;
  /** Issue codes open on the audit; a fix is only offered for something actually reported. */
  issueCodes: Set<string> | string[];
  /** Current file contents, null when the file does not exist. */
  existing: {
    indexHtml?: string | null;
    robotsTxt?: string | null;
    sitemapXml?: string | null;
    llmsTxt?: string | null;
  };
  /** URLs the audit saw, for the sitemap. The site URL alone is a valid sitemap. */
  pages?: string[];
  /** Meta description already on the page, if any. Never invented when absent. */
  description?: string | null;
}

export interface DeterministicFile {
  path: string;
  content: string;
  message: string;
  /** 'created' for a new file, 'edited' for an insertion into an existing one. */
  action: 'created' | 'edited';
}

export interface DeterministicFixes {
  files: DeterministicFile[];
  /** Issue codes these files address, for the PR body and issue bookkeeping. */
  addressed: string[];
  summary: string;
}

function xmlEscape(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function sitemap(urls: string[]): string {
  const today = new Date().toISOString().slice(0, 10);
  const entries = urls
    .map(
      (url) => `  <url>
    <loc>${xmlEscape(url)}</loc>
    <lastmod>${today}</lastmod>
  </url>`
    )
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by RankCLI - https://rankcli.dev -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries}
</urlset>
`;
}

// llms.txt (llmstxt.org): what the site is and where to read it, for AI assistants. Only
// the facts we hold - no invented feature list, no invented description.
function llmsTxt(siteName: string, siteUrl: string, description: string | null | undefined, pages: string[]): string {
  const base = siteUrl.replace(/\/$/, '');
  const trim = (url: string) => url.replace(/\/$/, '');
  const links = pages
    .filter((url) => trim(url) !== base)
    .map((url) => ({ url, path: url.replace(base, '').replace(/^$/, '/') }))
    .filter((page) => page.path !== '/')
    .slice(0, 20)
    .map((page) => `- [${page.path}](${page.url})`)
    .join('\n');
  return `# ${siteName}

${description ? `> ${description}\n\n` : ''}${base}

## Pages
- [Home](${base}/)
${links}

<!-- Generated by RankCLI - https://rankcli.dev -->
`;
}

/** The JSON-LD block, as it is inserted into <head>. */
function jsonLdBlock(siteName: string, siteUrl: string, description: string | null | undefined): string {
  const base = siteUrl.replace(/\/$/, '');
  const graph = [
    generateWebSiteSchema({ name: siteName, url: base, ...(description ? { description } : {}) } as never),
    generateOrganizationSchema({ name: siteName, url: base, ...(description ? { description } : {}) } as never),
  ];
  return `    <script type="application/ld+json">\n${JSON.stringify(graph, null, 2)
    .split('\n')
    .map((line) => `    ${line}`)
    .join('\n')}\n    </script>\n`;
}

const SCHEMA_CODES = [
  'SCHEMA_MISSING',
  'SCHEMA_ORG_MISSING',
  'ORGANIZATION_SCHEMA_MISSING',
  'NO_ORGANIZATION_SCHEMA',
  'NO_ENTITY_SCHEMA',
  'STRUCTURED_DATA_MISSING',
];

/** The page's own meta description. Their copy, read - never written. */
export function metaDescriptionOf(html: string | null | undefined): string | null {
  if (!html) return null;
  const match =
    html.match(/<meta[^>]+name=["']description["'][^>]+content=["']([^"']+)["']/i) ||
    html.match(/<meta[^>]+content=["']([^"']+)["'][^>]+name=["']description["']/i);
  return match?.[1]?.trim() || null;
}

export function buildDeterministicFixes(input: DeterministicFixInput): DeterministicFixes {
  const codes = new Set(input.issueCodes);
  const has = (...wanted: string[]) => wanted.some((code) => codes.has(code));
  const root = input.appRoot || '';
  // Normalised so callers can pass 'public', 'public/' or ''.
  const publicDir = input.publicDir === undefined ? 'public/' : input.publicDir.replace(/\/?$/, input.publicDir ? '/' : '');
  const served = `${root}${publicDir}`;
  const files: DeterministicFile[] = [];
  const addressed: string[] = [];
  const base = input.siteUrl.replace(/\/$/, '');
  const pages = input.pages?.length ? input.pages : [`${base}/`];
  // Given one explicitly, use it; otherwise read the page's own.
  const description = input.description ?? metaDescriptionOf(input.existing.indexHtml);

  if (has('ROBOTS_TXT_MISSING', 'AI_BOTS_BLOCKED', 'AI_CRAWLERS_BLOCKED') && !input.existing.robotsTxt) {
    files.push({
      path: `${served}robots.txt`,
      content: generateAIFriendlyRobotsTxt(base),
      message: 'fix(seo): add robots.txt allowing search and AI crawlers',
      action: 'created',
    });
    addressed.push('ROBOTS_TXT_MISSING');
  }

  if (has('SITEMAP_MISSING') && !input.existing.sitemapXml) {
    files.push({
      path: `${served}sitemap.xml`,
      content: sitemap(pages),
      message: 'fix(seo): add sitemap.xml',
      action: 'created',
    });
    addressed.push('SITEMAP_MISSING');
  }

  if (has('LLMS_TXT_MISSING') && !input.existing.llmsTxt) {
    files.push({
      path: `${served}llms.txt`,
      content: llmsTxt(input.siteName, base, description, pages),
      message: 'fix(seo): add llms.txt for AI assistants',
      action: 'created',
    });
    addressed.push('LLMS_TXT_MISSING');
  }

  // The only existing file touched, and only by insertion. Skipped when the page already
  // carries JSON-LD: merging someone's structured data is a judgement call, not a template.
  const indexHtml = input.existing.indexHtml;
  if (
    has(...SCHEMA_CODES) &&
    indexHtml &&
    !indexHtml.includes('application/ld+json') &&
    indexHtml.includes('</head>')
  ) {
    files.push({
      path: `${root}index.html`,
      content: indexHtml.replace('</head>', `${jsonLdBlock(input.siteName, base, description)}  </head>`),
      message: 'fix(seo): add WebSite and Organization JSON-LD',
      action: 'edited',
    });
    addressed.push(...SCHEMA_CODES.filter((code) => codes.has(code)));
  }

  const name = (file: DeterministicFile) => file.path.split('/').pop();
  const created = files.filter((f) => f.action === 'created').map(name);
  const edited = files.filter((f) => f.action === 'edited').map(name);
  const parts = [
    created.length ? `Added ${created.join(', ')}` : null,
    edited.length ? `updated ${edited.join(', ')}` : null,
  ].filter(Boolean);
  const summary = files.length
    ? `${parts.join('; ')} from RankCLI's templates - generated from the site's URL and name, with no AI and nothing invented.`
    : 'No template-generatable issues were open on this report.';

  return { files, addressed, summary };
}
